export function getRandomAdedTopic(usedTopics = []) {
  const usedSet = new Set(usedTopics);
  const available = ADED_TOPICS.filter(t => !usedSet.has(t));
  const pool = available.length > 0 ? available : ADED_TOPICS;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
