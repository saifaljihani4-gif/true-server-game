export function makeCards(mode: Mode): Card[] {
  switch (mode) {
    case 'dialects':
      return Array.from({ length: 40 }, (_, i) => blank(i + 1, 'تحدي اللهجات', { title: '...' }));

    case 'letters': {
      const letters = shuffled(bannedLetters);
      const topics = shuffled(banTopics);
      return Array.from({ length: 40 }, (_, i) =>
        blank(i + 1, 'حرف ممنوع', {
          title: letters[i % letters.length],
          desc: 'ممنوع تنطق هذا الحرف',
          hint: `احكِ عن: ${topics[i % topics.length]}`,
        }));
    }

    case 'gibberish': {
      const generated = gibberishSentences.map(s => [scramble(s), s] as [string, string]);
      return shuffled([...handmadeGibberish, ...generated]).slice(0, 40).map(([title, answer], i) =>
        blank(i + 1, 'تحدي الطلاسم', { title, desc: 'اكتشف الجملة المخفية', answer, tag: difficulty(answer) }));
    }

    case 'improv':
      return shuffled(improvWords).map((title, i) => {
        const genre = pick(improvGenres);
        return blank(i + 1, 'الكلمة المحشورة', { title, desc: 'ألّف قصة بهذا النوع واحشر الكلمات الثلاث فيها', tag: genre });
      });

    case 'taboo':
      return shuffled(tabooWords).map(([title, banned], i) =>
        blank(i + 1, 'قلها بدون ما تقولها', { title, desc: 'وصّفها بدون الكلمات الممنوعة', hint: `ممنوع: ${banned.join('، ')}` }));

    case 'emoji':
      return shuffled(emojiPuzzles).map(([title, answer, tag], i) =>
        blank(i + 1, 'خمّن من الإيموجي', { title, desc: 'وش المقصود؟', answer, tag }));

    case 'lists':
      return Array.from({ length: 40 }, (_, i) => {
        const n = pick([4, 5, 6]);
        const withLetter = Math.random() < 0.55;
        return blank(i + 1, 'سباق القوائم', {
          title: `اذكر ${n} ${pick(listCategories)}`,
          desc: withLetter ? `كلها تبدأ بحرف ${pick(listLetters)}` : 'بأسرع وقت',
        });
      });

    
    case 'series':
      return shuffled(seriesPuzzles).map(([title, answer], i) =>
        blank(i + 1, 'خمن المسلسل', { title, desc: 'من الإيموجي.. وش اسم هذا المسلسل أو الفيلم؟', answer }));

    case 'sell':
      return shuffled(sellItems).map((title, i) =>
        blank(i + 1, 'بيّع لي', { title, desc: `بيّعها ${pick(sellAudiences)}` }));
  }
}
