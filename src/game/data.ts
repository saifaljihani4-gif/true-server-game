export function fillDialectCard(card: Card, duel: boolean): Card {
  const d1 = pick(dialectNames);
  let d2 = pick(dialectNames);
  while (d2 === d1) d2 = pick(dialectNames);
  const hint = pick(dialectSentences);
  return duel
    ? { ...card, type: 'تحدي مزدوج', title: `${d1} VS ${d2}`, desc: 'كل واحد يقولها بلهجته', hint }
    : { ...card, type: 'تحدي فردي', title: d1, desc: 'قل الجملة بهذي اللهجة', hint };
}

