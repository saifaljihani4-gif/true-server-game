/** يقطّع الجملة بعد ما يحذف المسافات، بحيث ما تطابق حدود الكلمات الأصلية */
export function scramble(sentence: string): string {
  const words = sentence.trim().split(/\s+/);
  const letters = Array.from(words.join(''));
  const original = new Set<number>();
  let acc = 0;
  words.forEach((w, i) => {
    acc += Array.from(w).length;
    if (i < words.length - 1) original.add(acc);
  });
  for (let attempt = 0; attempt < 24; attempt++) {
    const chunks: string[] = [];
    const cuts = new Set<number>();
    let i = 0;
    while (i < letters.length) {
      const remaining = letters.length - i;
      let size = 2 + Math.floor(Math.random() * 3);
      if (remaining - size === 1) size = remaining;
      if (size > remaining) size = remaining;
      chunks.push(letters.slice(i, i + size).join(''));
      i += size;
      if (i < letters.length) cuts.add(i);
    }
    const same = cuts.size === original.size && [...cuts].every(c => original.has(c));
    if (!same && chunks.length >= 2) return chunks.join(' ');
  }
  return letters.join(' ');
}

